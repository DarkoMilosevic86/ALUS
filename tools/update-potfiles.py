# Writes (or checks) po/POTFILES.in.
#
# WHY THIS IS A SCRIPT AND A TEST, and not a list someone remembers to edit.
# A file missing from POTFILES.in produces no error anywhere: the build
# succeeds, the catalogue is valid, msgfmt is happy, and the strings in that
# file are simply never offered to a translator and are spoken in English
# forever. That is the single most likely way for localization to rot, so the
# list is generated from the sources and `--check` fails the build when the two
# disagree.
"""Keep po/POTFILES.in in step with the sources that use the i18n macros."""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

# `_(`, `N_(`, `C_(`, `NC_(`, `P_(` -- but not `gettext_(` or a member `x._(`.
MACRO = re.compile(r"(?<![\w.>])(?:_|N_|C_|NC_|P_)\s*\(")

HEADER = """# SPDX-License-Identifier: GPL-2.0-or-later
# ALUS translatable sources -- GENERATED by tools/update-potfiles.py.
#
# Every source file that uses _(), N_(), C_(), NC_() or P_(). Regenerate with
#   python3 tools/update-potfiles.py
# and check it in CI with
#   python3 tools/update-potfiles.py --check
# A file missing here is a file whose strings no translator ever sees.
"""


def scan(root: Path) -> list[str]:
    found = []
    for path in sorted(root.rglob("*")):
        if path.suffix not in {".cpp", ".hpp", ".c", ".h"}:
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        # Strip // comments and "quoted text" before looking for the macros, so
        # that a comment mentioning _("...") does not add a file that has no
        # translatable string of its own (src/script/dispatch.cpp used to).
        stripped = re.sub(r"//[^\n]*", "", text)
        stripped = re.sub(r'"(?:[^"\\\n]|\\.)*"', '""', stripped)
        if MACRO.search(stripped):
            found.append(path.as_posix())
    return found


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", default="src", type=Path)
    parser.add_argument("--out", default="po/POTFILES.in", type=Path)
    parser.add_argument("--check", action="store_true",
                        help="exit non-zero if the file is out of date")
    args = parser.parse_args()

    files = scan(args.root)
    body = HEADER + "\n" + "\n".join(files) + "\n"

    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.exists() else ""
        if current == body:
            print(f"{args.out}: up to date ({len(files)} files)")
            return 0
        have = {line for line in current.splitlines()
                if line and not line.startswith("#")}
        want = set(files)
        for name in sorted(want - have):
            print(f"MISSING from {args.out}: {name}", file=sys.stderr)
        for name in sorted(have - want):
            print(f"STALE in {args.out}:   {name}", file=sys.stderr)
        if have == want:
            print(f"{args.out}: same files, different formatting", file=sys.stderr)
        print("run: python3 tools/update-potfiles.py", file=sys.stderr)
        return 1

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(body, encoding="utf-8")
    print(f"{args.out}: {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
