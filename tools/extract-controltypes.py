#   /usr/include/at-spi-2.0/atspi/atspi-constants.h
#                                      -> alus::a11y::PlatformRole,
#                                         PlatformState, PlatformRelation
#
# Why generated (same reason as tools/extract-commands.py in phase 3): these
# are ~390 names, each of which must match its source exactly. A typo in a role
# label is a word a blind user hears wrong, and a typo in a platform enumerator
# is a silent mis-mapping of every object with that role.
#
# The AT-SPI -> ALUS MAPPING IS NOT GENERATED. It is a semantic decision per
# role and lives in src/a11y/role_map.cpp and src/a11y/state_map.cpp, with a
# test that every platform value is covered (T4.6).
#
# Usage:
#   python3 tools/extract-controltypes.py --source ./NVDA \
#       [--atspi /usr/include/at-spi-2.0/atspi/atspi-constants.h] [--check]

