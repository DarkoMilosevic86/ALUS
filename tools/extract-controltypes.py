def camel(name: str) -> str:
    if name in OVERRIDES:
        return OVERRIDES[name]
    words = []
    for part in name.split("_"):
        rest = part
        while rest:
            for word in sorted(VOCABULARY, key=len, reverse=True):
                if rest.startswith(word):
                    words.append(word.capitalize())
                    rest = rest[len(word):]
                    break
            else:
                # Unsplittable tail: keep it as one capitalised word.
                words.append(rest.capitalize())
                rest = ""
    return "".join(words)


def atspi_camel(name: str, prefix: str) -> str:
    body = name[len(prefix):]
    return "".join(part.capitalize() for part in body.split("_"))


def parse_atspi_enum(text: str, type_name: str, prefix: str):
    # [^}] keeps the match inside ONE typedef; the header has a dozen of them.
    match = re.search(r"typedef enum\s*\{([^}]*)\}\s*" + type_name + r";", text, re.S)
    if match is None:
        raise SystemExit(f"could not find {type_name} in the AT-SPI header")
    names = []
    for line in match.group(1).split("\n"):
        line = line.split("/*")[0].strip()
        item = re.match(r"^(" + prefix + r"[A-Z0-9_]*),?$", line)
        if item is None:
            continue
        name = item.group(1)
        if name.endswith("_LAST_DEFINED"):
            break
        names.append(name)
    return names


def parse_labels(text: str, dict_name: str, kind: str):
    match = re.search(r"^" + dict_name + r"[^=]*= \{\n(.*?)^\}", text, re.S | re.M)
    if match is None:
        raise SystemExit(f"could not find {dict_name}")
    labels = {}
    pattern = re.compile(
        r"^\t" + kind + r"\.([A-Z][A-Z0-9_]*): (?:_|pgettext|ngettext)\(\s*(.*?)\s*\),?$",
        re.M | re.S,
    )
    for name, literal in pattern.findall(match.group(1)):
        literal = literal.strip()
        # A plain single-quoted or double-quoted Python string, possibly with
        # adjacent concatenated parts.
        parts = re.findall(r'"((?:[^"\\]|\\.)*)"|\'((?:[^\'\\]|\\.)*)\'', literal)
        if not parts:
            raise SystemExit(f"{dict_name}: cannot read the label of {name}: {literal}")
        if literal.startswith(("\"controlType\"", "'controlType'")):
            # pgettext(context, label): the context is not part of the label.
            parts = parts[1:]
        labels[name] = "".join(a or b for a, b in parts)
    return labels


def parse_set(text: str, set_name: str, kind: str):
    match = re.search(
        r"^" + set_name + r"[^=\n]*=\s*(?:frozenset\(|set\()?[\{\[]\n(.*?)\n[\}\]]",
        text, re.S | re.M)
    if match is None:
        raise SystemExit(f"could not find {set_name}")
    return re.findall(kind + r"\.([A-Z][A-Z0-9_]*)", match.group(1))


def cpp_string(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def write(path: Path, content: str, check: bool) -> bool:
    existing = path.read_text(encoding="utf-8") if path.exists() else None
    if existing == content:
        print(f"  unchanged  {path}")
        return True
    if check:
        print(f"  STALE      {path}", file=sys.stderr)
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    print(f"  written    {path}")
    return True


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", default="./reference/nvda", type=Path,
                        help="the upstream source tree; the checked-in subset "
                             "in reference/nvda by default")
    parser.add_argument("--atspi", type=Path,
                        default=Path("/usr/include/at-spi-2.0/atspi/atspi-constants.h"))
    parser.add_argument("--out", type=Path, default=Path("."),
                        help="the ALUS source root")
    parser.add_argument("--check", action="store_true",
                        help="fail if the generated files are out of date")
    args = parser.parse_args()

    control_types = args.source / "source" / "controlTypes"
    role_py = (control_types / "role.py").read_text(encoding="utf-8")
    state_py = (control_types / "state.py").read_text(encoding="utf-8")
    atspi_h = args.atspi.read_text(encoding="utf-8")

    roles = re.findall(r"^\t([A-Z][A-Z0-9_]*) = (\d+)\s*(?:#.*)?$", role_py, re.M)
    states = re.findall(r"^\t([A-Z][A-Z0-9_]*) = setBit\((\d+)\)\s*(?:#.*)?$", state_py, re.M)
    role_labels = parse_labels(role_py, "_roleLabels", "Role")
    state_labels = parse_labels(state_py, "_stateLabels", "State")
    negative_labels = parse_labels(state_py, "_negativeStateLabels", "State")
    silent_on_focus = parse_set(role_py, "silentRolesOnFocus", "Role")
    silent_values = parse_set(role_py, "silentValuesForRoles", "Role")
    clickable = parse_set(role_py, "clickableRoles", "Role")

    platform_roles = parse_atspi_enum(atspi_h, "AtspiRole", "ATSPI_ROLE_")
    platform_states = parse_atspi_enum(atspi_h, "AtspiStateType", "ATSPI_STATE_")
    platform_relations = parse_atspi_enum(atspi_h, "AtspiRelationType", "ATSPI_RELATION_")

    print(f"NVDA: {len(roles)} roles, {len(states)} states")
    print(f"AT-SPI: {len(platform_roles)} roles, {len(platform_states)} states, "
          f"{len(platform_relations)} relations")

    missing = [name for name, _ in roles if name not in role_labels]
    if missing:
        raise SystemExit(f"roles without a label: {missing}")
    # Two states have no label in NVDA and are not meant to be spoken:
    # HAS_ARIA_DETAILS (kept for add-on compatibility only) and INDETERMINATE
    # (processAndLabelStates discards it; transformRoleStates turns it into
    # Role.BUSY_INDICATOR instead). They keep an empty label here, and
    # stateLabel() returning "" is how the presentation layer sees that.
    unlabelled = [name for name, _ in states if name not in state_labels]
    if sorted(unlabelled) != ["HAS_ARIA_DETAILS", "INDETERMINATE"]:
        raise SystemExit(f"unexpected states without a label: {unlabelled}")
    print(f"states deliberately without a label: {', '.join(sorted(unlabelled))}")
    for name in unlabelled:
        state_labels[name] = ""

    ok = True
    ok &= write(args.out / "include" / "alus" / "a11y" / "role.hpp",
                role_header(roles), args.check)
    ok &= write(args.out / "src" / "a11y" / "role_tables.cpp",
                role_tables(roles, role_labels, silent_on_focus, silent_values, clickable),
                args.check)
    ok &= write(args.out / "include" / "alus" / "a11y" / "state.hpp",
                state_header(states), args.check)
    ok &= write(args.out / "src" / "a11y" / "state_tables.cpp",
                state_tables(states, state_labels, negative_labels), args.check)
    ok &= write(args.out / "include" / "alus" / "a11y" / "platform.hpp",
                platform_header(platform_roles, platform_states, platform_relations),
                args.check)
    ok &= write(args.out / "src" / "a11y" / "platform_tables.cpp",
                platform_tables(platform_roles, platform_states, platform_relations),
                args.check)
    return 0 if ok else 1


