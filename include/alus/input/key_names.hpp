// Key names: keysym <-> NVDA name <-> spoken label.
//
// Port of NVDA's `vkCodes.py` and `keyLabels.py` onto X11 keysyms
// (01-ARHITEKTURA.md §5.2). The NAMES ARE USER INTERFACE: they appear in
// `gestures.ini`, in the generated command reference and in the gesture
// dialog, so they must be NVDA's spelling exactly — "numpad7", "leftArrow",
// "numpadInsert" — or a user's own NVDA gesture map stops working (Z3).
//
// Two things make this simpler on Linux than on Windows:
//
//   1. With NumLock OFF the numeric keypad reports NAMED keysyms (`KP_Home`,
//      not `KP_7`), so the numpad-versus-navigation distinction needs no
//      extended-key bit the way NVDA's `(vkCode, extended)` pairs do.
//   2. The compositor hands us the character the key produced (`unichar`), so
//      no keyboard-layout translation of our own is needed to name a letter
//      key or to echo a typed character.
//
// What still needs a library is the other direction: a gesture written
// `kb(laptop):nvda+š` has to become the keysym the compositor will compare a
// grab against, and that is the LEGACY keysym (`XK_scaron`, 0x1b9), not the
// Unicode form 0x1000161. libxkbcommon does that conversion, and it is the
// same library the compositor uses, so the two cannot drift apart.
#pragma once

#include "alus/input/keysyms.hpp"

#include <cstdint>
#include <filesystem>
#include <optional>
#include <string>
#include <string_view>
#include <unordered_map>
#include <vector>

namespace alus::input {

// The generalized modifiers of a gesture. NVDA generalizes leftControl and
// rightControl into one "control" before building an identifier, because a
// user binds `control+f`, never `leftControl+f`.
enum class Modifier : std::uint32_t {
    None = 0,
    Shift = 1u << 0,
    Control = 1u << 1,
    Alt = 1u << 2,
    Windows = 1u << 3,
    // The ALUS key (NVDA key): insert, numpad insert and/or caps lock. Not a
    // real modifier anywhere in the system — the compositor is made to treat
    // it as one through a virtual modifier (§5.2, N9).
    Alus = 1u << 4,
    // NumLock counts as a modifier only for the keypad keys that report the
    // same keysym either way (`KP_Multiply` and friends), exactly as NVDA
    // does for their shared vkCodes.
    NumLock = 1u << 5,
};

using Modifiers = std::uint32_t;

constexpr Modifiers operator|(Modifier a, Modifier b) noexcept {
    return static_cast<Modifiers>(a) | static_cast<Modifiers>(b);
}
constexpr Modifiers operator|(Modifiers a, Modifier b) noexcept {
    return a | static_cast<Modifiers>(b);
}
constexpr Modifiers& operator|=(Modifiers& a, Modifier b) noexcept {
    a = a | static_cast<Modifiers>(b);
    return a;
}
constexpr bool has(Modifiers set, Modifier m) noexcept {
    return (set & static_cast<Modifiers>(m)) != 0;
}

class KeyNames {
public:
    KeyNames();

    // The process-wide table. The input service loads the spoken labels into
    // it at start-up; everything else only reads it.
    static KeyNames& shared();

    // The NVDA name of a key. `unichar` is the character the compositor says
    // the key produced (0 when it produced none) and is used only when the
    // keysym has no name of its own, which is the case for every letter,
    // digit and punctuation key. An unnamed key becomes "unknown_<hex>", as in
    // NVDA, so that it can still be bound and still be reported.
    std::string name(std::uint32_t keysym, std::uint32_t unichar = 0) const;

    // The keysym for a key name, for building a grab out of a gesture
    // identifier. Returns nothing for a name no keyboard can produce.
    std::optional<std::uint32_t> keysym(std::string_view name) const;

    // "capsLock" -> "caps lock". Falls back to the name itself, which is the
    // right answer for letters and digits.
    std::string label(std::string_view name) const;

    bool isNumpad(std::string_view name) const;
    // Keys that toggle: NVDA does not report them as commands, because the
    // state change is announced separately (`keyboardHandler.TOGGLE_KEYS`).
    bool isToggle(std::string_view name) const;
    // A key that is only ever a modifier: no script is looked up for it.
    std::optional<Modifier> modifierFor(std::string_view name) const;

    // data/key-labels.ini, generated by tools/extract-nvda-commands.py.
    bool loadLabels(const std::filesystem::path& path, std::string* error = nullptr);
    void setLabel(std::string name, std::string label);
    std::size_t labelCount() const noexcept { return labels_.size(); }

    // The X11 modifier state mask the compositor reports, turned into ALUS
    // modifiers. `alusVirtualModifierMask` is what
    // `atspi_device_map_keysym_modifier` returned for the ALUS key — a mask,
    // never an index (N9). Mod5/AltGr is deliberately NOT a modifier here:
    // it composes characters, and treating it as "alt" would turn every
    // AltGr-typed character into a command.
    static Modifiers modifiersFromState(std::uint32_t state,
                                        std::uint32_t alusVirtualModifierMask = 0);

    // The names of the modifiers in a fixed order. NVDA iterates a Python set
    // here, so its display order is arbitrary; ALUS fixes the order, because
    // "insert+control+t" and "control+insert+t" read differently to a user
    // hearing them and identically to the gesture map.
    static std::vector<std::string> modifierNames(Modifiers modifiers);

    // The name of ALUS's own key inside a gesture identifier: `kb:alus+t`.
    // This is ALUS's screen reader, so this is ALUS's key, and nothing ALUS
    // writes or says names another product.
    static constexpr std::string_view kAlusKeyName = "alus";

    // The spelling an imported gesture map may use for the same key. A user
    // arriving with their own map has `kb:NVDA+tab` in it, and 00-VIZIJA.md Z3
    // promises that file loads WITHOUT EDITS — so the old name is accepted on
    // the way IN, canonicalised to `alus` by normalizeGestureIdentifier, and
    // never written back out. Read-only compatibility, in exactly one place.
    static constexpr std::string_view kImportedAlusKeyName = "nvda";

private:
    struct NameEntry {
        std::uint32_t keysym;
        std::string_view name;
    };

    void addRange(std::uint32_t firstKeysym, std::uint32_t lastKeysym,
                  std::string_view prefix, int firstIndex);

    std::unordered_map<std::uint32_t, std::string> byKeysym_;
    // Lower-cased name -> keysym. Gesture identifiers are lower-cased by
    // normalization, so every lookup here is case insensitive by construction.
    std::unordered_map<std::string, std::uint32_t> byName_;
    std::unordered_map<std::string, std::string> labels_;
};

}  // namespace alus::input
